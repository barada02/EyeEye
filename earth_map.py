def _inside(poly, lon, lat):
    """Even-odd point-in-polygon test for every (lon, lat) grid point."""
    p = np.asarray(poly, np.float32)
    hit = np.zeros(lat.shape + lon.shape, bool)
    x, y = lon[None, :], lat[:, None]
    for (x0, y0), (x1, y1) in zip(p, np.roll(p, -1, axis=0)):
        if y0 != y1:
            hit ^= ((y0 > y) != (y1 > y)) & (x < x0 + (y - y0) * (x1 - x0) / (y1 - y0))
    return hit


def land_mask(w=512, h=256):
    """(h, w) float mask, 1 on land, with softened coasts. Row 0 is the north pole."""
    lon = ((np.arange(w) + 0.5) / w * 360 - 180).astype(np.float32)
    lat = (90 - (np.arange(h) + 0.5) / h * 180).astype(np.float32)
    land = np.zeros((h, w), bool)
    for poly, keep in [(p, True) for p in LAND] + [(p, False) for p in WATER]:
        p = np.asarray(poly)
        cols = (lon >= p[:, 0].min() - 1) & (lon <= p[:, 0].max() + 1)
        rows = (lat >= p[:, 1].min() - 1) & (lat <= p[:, 1].max() + 1)
        sub = _inside(poly, lon[cols], lat[rows])
        block = np.ix_(rows, cols)
        land[block] = (land[block] | sub) if keep else (land[block] & ~sub)
    land |= lat[:, None] < -72 + 3 * np.sin(np.radians(lon[None, :]) * 3)    # Antarctica
    m = land.astype(np.float32)
    for _ in range(3):
        m = (m + np.roll(m, 1, 0) + np.roll(m, -1, 0) + np.roll(m, 1, 1) + np.roll(m, -1, 1)) / 5
    return m
